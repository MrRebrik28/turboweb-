def generate_step1_ping(group_data: Dict[str, Any], niche: str = "услуг", city: str = "") -> str:
    """
    Генерирует короткий естественный вопрос Шага 1 («Касание без продажи»).
    Не содержит ссылок, названий студий и цен.
    """
    site = (group_data.get("site") or "").strip().lower()

    if not site or "vk.com" in site:
        template = random.choice(PING_TEMPLATES_NO_SITE)
    else:
        template = random.choice(PING_TEMPLATES_WITH_SITE + PING_TEMPLATES_NO_SITE)

    raw_text = resolve_spintax(template).strip()
    return raw_text


