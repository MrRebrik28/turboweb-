def generate_step2_pitch(group_data: Dict[str, Any], niche: str = "вашей сферы", city: str = "") -> str:
    """
    Генерирует коммерческое предложение Шага 2 для отправки во ВЗАИМНЫЙ диалог.
    """
    raw_name = group_data.get("name", "")
    clean_name = clean_group_name(raw_name)
    site = (group_data.get("site") or "").strip().lower()

    if not site or "vk.com" in site:
        template = STEP2_TEMPLATE_NO_SITE
    else:
        template = STEP2_TEMPLATE_WITH_SITE

    template = template.replace("[NICHE]", niche).replace("[BRAND]", clean_name)
    resolved = resolve_spintax(template)
    resolved = re.sub(r'\n{3,}', '\n\n', resolved).strip()
    return resolved

# Для обратной совместимости
def generate_personalized_pitch(group_data: Dict[str, Any], niche: str = "вашей сферы", city: str = "") -> str:
    return generate_step2_pitch(group_data, niche=niche, city=city)
