"""
LocalWeb VK Outreach — Генератор уникальных сообщений для 2-шаговой стратегии (Spintax).

Стратегия «Касание без продажи»:
- Шаг 1 (Пинг): Короткий естественный вопрос под видом клиента или партнера.
  БЕЗ ссылок, БЕЗ спам-слов («разработка», «лендинг», «7500»). Пробивает антиспам ВК.
- Шаг 2 (Оффер): Отправляется ТОЛЬКО ПОСЛЕ ОТВЕТА сообщества, когда диалог официально
  стал взаимным для алгоритмов ВК. Спам-фильтр отключается, можно спокойно присылать оффер.
"""

import re
import random
from typing import Dict, Any, Optional

def clean_group_name(raw_name: str) -> str:
    """
    Очищает название группы от спам-хвостов, городов, капслока и эмодзи,
    чтобы оно звучало естественно в живом обращении.
    Пример: 'НА БРОНЕ | ПРЕМИУМ ДЕТЕЙЛИНГ | КЕМЕРОВО' -> '«На Броне»'
    """
    if not raw_name:
        return "вашей компании"

    clean = re.sub(r'[\U00010000-\U0010ffff]', '', raw_name, flags=re.UNICODE)
    clean = re.sub(r'[\u2600-\u27ff]', '', clean)
    clean = clean.strip()

    parts = re.split(r'\s*[|/•~—]\s*|\s+-\s+', clean)
    if parts and len(parts[0].strip()) >= 3:
        clean = parts[0].strip()

    clean = clean.strip('"\'«»„“')

    if clean.isupper() and len(clean) > 4:
        clean = clean.title()

    if not clean or len(clean) < 2:
        return "вашей компании"

    return f"«{clean}»"

def resolve_spintax(text: str) -> str:
    """
    Рекурсивно раскрывает спинтакс-шаблоны вида {вариант1|вариант2|вариант3}.
    Поддерживает вложенные конструкции: {A|B {C|D}}
    """
    pattern = re.compile(r'\{([^{}]+)\}')
    while True:
        match = pattern.search(text)
        if not match:
            break
        options = match.group(1).split('|')
        chosen = random.choice(options)
        text = text[:match.start()] + chosen + text[match.end():]
    return text


